'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const {create,expect} = require('./ui-session.cjs');
const {pdfFixture} = require('./fixtures.cjs');
const {clickTool} = require('./read-map-actions.cjs');
(async()=>{
  const f=await create('reader-request-regressions-ui');let failure;
  try {
    const {page,api,workspace,pass}=f;
    await fs.writeFile(path.join(workspace,'Source.pdf'),pdfFixture());
    await fs.writeFile(path.join(workspace,'Reading.html'),'<h1>Chapter</h1><p>Reflowable text for reader gestures and covers.</p>');
    let set=await api('study.create',{title:'Document and mindmap regression'});
    set=await api('study.documents.add',{setId:set.id,expectedRevision:set.revision,paths:['Source.pdf','Reading.html']});
    const doc=set.documents.find(item=>item.path==='Source.pdf');
    await api('study.open',{setId:set.id,documentId:doc.id});
    await page.goto(f.server.url);
    await page.locator('body[data-ready=true]').waitFor();
    await expect(page.locator('#reader-view')).toBeVisible();
    await expect(page.locator('#pdf-page-progress')).toBeVisible();
    assert.equal(await page.locator('#pdf-page-progress').getAttribute('type'),'range');
    await expect(page.locator('.pdf-page canvas').first()).toBeVisible();
    await page.evaluate(()=>document.getElementById('toggle-outline').click());
    await expect(page.locator('#outline-pane')).toBeVisible();
    const bounds=()=>page.evaluate(()=>{
      const r=id=>{const a=document.getElementById(id).getBoundingClientRect();return{x:a.x,y:a.y,right:a.right,bottom:a.bottom,width:a.width,height:a.height};};
      return{scroll:r('reader-scroll'),outline:r('outline-pane'),viewport:r('reader-view')};
    });
    let b=await bounds();assert(b.outline.x>=b.scroll.right-1,JSON.stringify(b));
    await page.locator('[data-outline-place=left]').click();
    await expect.poll(async()=>(await api('settings.get')).outlineSide).toBe('left');
    await expect.poll(async()=>page.locator('#workspace').getAttribute('data-outline-side')).toBe('left');
    b=await bounds();assert(b.outline.right<=b.scroll.x+1,JSON.stringify(b));
    await page.setViewportSize({width:780,height:850});
    b=await bounds();assert(b.outline.right<=b.scroll.x+1&&b.scroll.width>200,JSON.stringify(b));
    await page.locator('[data-outline-place=right]').click();
    await expect.poll(async()=>(await api('settings.get')).outlineSide).toBe('right');
    await expect.poll(async()=>page.locator('#workspace').getAttribute('data-outline-side')).toBe('right');
    b=await bounds();assert(b.outline.x>=b.scroll.right-1&&b.scroll.width>200,JSON.stringify(b));
    pass('PDF progress is horizontal, and both TOC sides consume separate nonoverlapping width even at 780px');
    await page.setViewportSize({width:1440,height:900});
    await page.locator('#reader-scroll').evaluate(el=>{
      const r=el.getBoundingClientRect();el.dispatchEvent(new WheelEvent('wheel',{bubbles:true,cancelable:true,ctrlKey:true,deltaY:-70,clientX:r.x+r.width/2,clientY:r.y+r.height/2}));
    });
    await expect.poll(async()=>(await api('settings.get')).pdfZoom,{timeout:10000}).toBeGreaterThan(1);
    pass('Ctrl + two-finger wheel magnifies the PDF, commits one bounded PDF zoom preference');
    await expect(page.locator('#study-palette select')).toHaveCount(0);
    await page.click('#study-back-set');
    await expect(page.locator('#study-add-documents')).toBeVisible();
    await page.click('#study-add-documents');
    await expect(page.locator('.study-file-picker')).toBeVisible();
    await expect(page.locator('.study-file-choice')).toHaveCount(2);
    await expect(page.locator('.study-file-choice[data-preview=ready]')).toHaveCount(2,{timeout:25000});
    assert.equal(await page.locator('.study-file-choice img.document-thumbnail').count(),2);
    assert.equal(await page.locator('.study-file-picker').evaluate(el=>getComputedStyle(el).display),'grid');
    assert((await page.locator('#dialog').boundingBox()).width>=650);
    await page.click('#dialog-cancel');
    pass('Study add-files dialog displays actual PDF and HTML cover thumbnails in a wide selectable grid');
    set=await api('study.get',{setId:set.id});
    await api('study.mindmap.outline.import',{setId:set.id,expectedRevision:set.revision,text:'# Main topic\n## Subtopic\n\nNote body'});
    set=await api('study.get',{setId:set.id});
    await api('study.view.set',{setId:set.id,expectedRevision:set.revision,view:'map'});
    await expect(page.locator('#mm-export')).toBeVisible();
    await clickTool(page,'mm-export');
    await expect(page.locator('#dialog [name=format] option[value=md]')).toHaveCount(1);
    await page.selectOption('#dialog [name=format]','md');
    await page.fill('#dialog [name=path]','mindmap-notes.md');
    await page.click('#dialog-submit');
    await expect(page.locator('#dialog')).toBeHidden();
    const md=await fs.readFile(path.join(workspace,'mindmap-notes.md'),'utf8');
    assert(md.includes('Main topic')&&md.includes('Subtopic')&&md.includes('Note body'));
    pass('Mind-map Markdown export preserves topic hierarchy and text in a real editable .md file');
    await page.context().grantPermissions(['clipboard-read','clipboard-write']);
    set=await api('study.get',{setId:set.id});
    await expect(page.locator('#study-board')).toHaveAttribute('data-rendered-study-revision',String(set.revision));
    await clickTool(page,'mm-copy-markdown');
    await expect.poll(async()=>page.evaluate(async()=>{
      const copied=await navigator.clipboard.readText();
      return copied.includes('Main topic')&&copied.includes('Subtopic')&&copied.includes('Note body');
    }),{timeout:10000}).toBe(true);
    pass('Copy as Markdown keeps both parent-child headings and note text on the clipboard');
  }catch(e){failure=e;}
  await f.finish(failure);
})().catch(error=>{console.error(error);process.exitCode=1;});
