function safeWrite(root:string,file:string,content:string,executable=false){
 if(fs.existsSync(file)&&fs.lstatSync(file).isSymbolicLink())throw Error('Cannot replace a bootstrap symlink')
 let parent=path.dirname(file);while(!fs.existsSync(parent))parent=path.dirname(parent)
 const actual=fs.realpathSync(parent)
 if(actual!==root&&!actual.startsWith(root+path.sep))throw Error('Bootstrap path points outside its runtime root')
 fs.mkdirSync(path.dirname(file),{recursive:true})
 if(fs.existsSync(file)&&fs.readFileSync(file,'utf8')===content)return
 fs.writeFileSync(file,content,{mode:executable?0o755:0o644});if(executable)fs.chmodSync(file,0o755)
}
/** Runtime launchers are not copied into an employee's working documents. */
export function ensureCompanyLauncher(){
 fs.mkdirSync(APP_HOME,{recursive:true});const root=fs.realpathSync(APP_HOME),directory=path.join(root,'cli'),cli=path.join(applicationRoot(),'bin/agents')
 writeWindowsCompanyLauncher(root,directory,cli,safeWrite)
 safeWrite(root,path.join(directory,'bin','agents'),`#!/bin/sh
# Generated by Aexus Bot; uses only the identity assigned to this process.
if [ -z "$AGENTS_COMPANY_TOKEN_FILE" ] && [ -z "$AGENTS_COMPANY_TOKEN" ]; then
  echo 'Agent identity missing; reopen this employee in Aexus Bot.' >&2; exit 2
fi
exec env ELECTRON_RUN_AS_NODE=1 ${quote(process.execPath)} ${quote(cli)} "$@"
`,true)
 return path.join(directory,'bin','agents'+(process.platform==='win32'?'.cmd':''))
}

/** Exactly one routing prompt, independent of role, team, plugin and employee identity. */
export function employeeInstructions(card:StoredSession,store:Store,_cli?:string){assertManagementKind(card,hasGlobalRole(store.access,card),employeeSettings(store,card).mode==='cloud');return ROUTER_PROMPT}


export function ensureEmployeeBootstrap(card:StoredSession,store=readStore()){
 const settings=employeeSettings(store,card),root=employeeRoot(store,card)
 if(!root)throw Error('Employee Team has no working directory')
 const instructions=employeeInstructions(card,store)
 const documentation=ensureApiDocuments(),launcher=ensureCompanyLauncher()
 if(settings.mode!=='cloud'){
  const cwd=fs.realpathSync(card.cwd);retireRootInstructions(cwd)
  if(settings.mode==='work'){
   const plugin=requirePlugin(settings.pluginId!),runtimeRoot=fs.realpathSync(APP_HOME),directory=path.join(runtimeRoot,'agent-access',card.id),cli=pluginFile(plugin.directory,plugin.cli)
   writeWindowsPluginLauncher(cwd,directory,root,plugin.id,cli,(ignored,file,content,executable)=>safeWrite(runtimeRoot,file,content,executable))
   safeWrite(runtimeRoot,path.join(directory,'bin',plugin.id),`#!/bin/sh
# Generated by Aexus Bot; bound to this employee workspace.
for argument in "$@"; do
  case "$argument" in --workspace|--workspace=*) echo 'Workspace is already bound to this employee.' >&2; exit 2 ;; esac
done
export AGENTS_WORKSPACE=${quote(cwd)}
export AGENTS_TEAM_ROOT=${quote(root)}
export AGENTS_COMPANY_PLUGIN_RPC=${quote(path.join(directory,'ipc',plugin.id))}
exec env ELECTRON_RUN_AS_NODE=1 ${quote(process.execPath)} ${quote(cli)} --workspace ${quote(cwd)} "$@"
`,true)
  }
 }
 return {mode:settings.mode,workspace:card.cwd,teamRoot:root,plugins:settings.mode==='work'?[settings.pluginId!]:[],instructions,documentation,launcher}
}

export function provisionEmployee(cwd:string,root:string,settings:TeamSettings){
 const store=readStore(),cards=store.sessions.filter(card=>card.cwd===cwd&&!card.deleting)
 if(cards.length){for(const card of cards)ensureEmployeeBootstrap(card,store);return {mode:settings.mode,workspace:cwd,teamRoot:root,plugins:settings.mode==='work'?[settings.pluginId!]:[]}}
 return settings.mode==='cloud'?{mode:settings.mode,workspace:cwd,teamRoot:root,plugins:[]}:provisionWorkspace(cwd,settings,root)
}

